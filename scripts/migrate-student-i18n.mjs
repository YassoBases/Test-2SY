/** @type {{ en: Record<string, unknown>, ar: Record<string, unknown> }} */
const translations = {
  en: {},
  ar: {},
}

function set(path, en, ar) {
  const parts = path.split('.')
  for (const locale of ['en', 'ar']) {
    let cur = translations[locale]
    for (let i = 0; i < parts.length - 1; i++) {
      cur[parts[i]] = cur[parts[i]] ?? {}
      cur = cur[parts[i]]
    }
    cur[parts[parts.length - 1]] = locale === 'en' ? en : ar
  }
}

